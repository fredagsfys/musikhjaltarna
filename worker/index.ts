/**
 * Serves the static site and stores registrations from the purchase flow in D1.
 * Only `/api/*` reaches this code (`run_worker_first` in wrangler.jsonc); every other
 * request is served directly from the static assets. Behaviour on the page is tracked
 * in PostHog (src/lib/tracking.ts); this database holds the registrations themselves.
 *
 * No cookies, IP addresses or user agents are stored.
 */
import { isCtaId } from '../src/config/site';

interface Env {
  ASSETS: Fetcher;
  DB: D1Database;
}

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const UPDATE_STATUSES = new Set(['ja', 'nej']);
const MAX_BODY_BYTES = 4096;

/**
 * One row per submission (brief A §7). The id is generated by the browser and reused for
 * retries, so double clicks, reloads and network retries update the same row instead of
 * creating new ones. `update_status` starts as `inget_val` and becomes `ja` or `nej`.
 */
const SCHEMA = `CREATE TABLE IF NOT EXISTS registrations (
  id TEXT PRIMARY KEY,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  cta_id TEXT,
  is_test INTEGER NOT NULL DEFAULT 0,
  update_status TEXT NOT NULL DEFAULT 'inget_val' CHECK (update_status IN ('inget_val', 'ja', 'nej')),
  update_status_at TEXT,
  update_info_version TEXT
)`;

/**
 * Ad source, page version and analytics consent (brief B §2–3, §9), added after launch, so existing
 * tables get them too. `analytics_consent` is `granted`, `denied` or empty when undecided.
 */
const SOURCE_COLUMNS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'message_id', 'ad_id'] as const;
const ADDED_COLUMNS = [...SOURCE_COLUMNS, 'page_version', 'analytics_consent'];
const CONSENT_CHOICES = new Set(['granted', 'denied']);

async function migrate(db: D1Database) {
  await db.prepare(SCHEMA).run();
  const { results } = await db.prepare('PRAGMA table_info(registrations)').all<{ name: string }>();
  const existing = new Set(results.map((column) => column.name));
  const missing = ADDED_COLUMNS.filter((column) => !existing.has(column));
  if (missing.length > 0) {
    await db.batch(missing.map((column) => db.prepare(`ALTER TABLE registrations ADD COLUMN ${column} TEXT`)));
  }
}

// The table is created and migrated on first use per isolate, so deploys need no migration step.
let schemaReady: Promise<unknown> | undefined;
const ensureSchema = (db: D1Database) =>
  (schemaReady ??= migrate(db).catch((error) => {
    schemaReady = undefined;
    throw error;
  }));

class HttpError extends Error {
  constructor(
    readonly status: number,
    message = '',
  ) {
    super(message);
  }
}

const text = (value: unknown, max: number) => (typeof value === 'string' ? value.trim().slice(0, max) : '');

async function readBody(request: Request): Promise<Record<string, unknown>> {
  if (request.method !== 'POST') throw new HttpError(405);
  // Only the site itself may write; browsers always send Origin on POST.
  if (request.headers.get('Origin') !== new URL(request.url).origin) throw new HttpError(403);

  const raw = await request.text();
  if (raw.length > MAX_BODY_BYTES) throw new HttpError(413);
  let body: unknown;
  try {
    body = JSON.parse(raw);
  } catch {
    throw new HttpError(400, 'Invalid JSON');
  }
  if (!body || typeof body !== 'object') throw new HttpError(400, 'Expected an object');
  return body as Record<string, unknown>;
}

/** Creates the registration, or updates it when the same submission is sent again. */
async function saveRegistration(body: Record<string, unknown>, db: D1Database) {
  const id = text(body.id, 36);
  const name = text(body.name, 200);
  const email = text(body.email, 254);
  if (!UUID.test(id)) throw new HttpError(400, 'Invalid id');
  if (!name || !EMAIL.test(email)) throw new HttpError(400, 'Invalid name or e-mail');
  const source = body.source && typeof body.source === 'object' ? (body.source as Record<string, unknown>) : {};

  // The source is kept from the first submission: it describes how the visitor arrived. Consent follows
  // the latest submission, since the visitor may have decided in between.
  await db
    .prepare(
      `INSERT INTO registrations (id, name, email, cta_id, is_test, ${ADDED_COLUMNS.join(', ')})
       VALUES (?, ?, ?, ?, ?, ${ADDED_COLUMNS.map(() => '?').join(', ')})
       ON CONFLICT (id) DO UPDATE SET name = excluded.name, email = excluded.email, cta_id = excluded.cta_id,
         analytics_consent = excluded.analytics_consent`,
    )
    .bind(
      id,
      name,
      email,
      isCtaId(body.ctaId) ? body.ctaId : null,
      body.isTest === true ? 1 : 0,
      ...SOURCE_COLUMNS.map((column) => text(source[column], 200) || null),
      text(body.pageVersion, 40) || null,
      CONSENT_CHOICES.has(text(body.analyticsConsent, 8)) ? text(body.analyticsConsent, 8) : null,
    )
    .run();
}

/** Records ja or nej on an existing registration, with the version of the information shown. */
async function saveUpdateStatus(id: string, body: Record<string, unknown>, db: D1Database) {
  const status = text(body.status, 3);
  if (!UUID.test(id)) throw new HttpError(404);
  if (!UPDATE_STATUSES.has(status)) throw new HttpError(400, 'Invalid status');

  const result = await db
    .prepare(
      `UPDATE registrations SET update_status = ?, update_status_at = datetime('now'), update_info_version = ?
       WHERE id = ?`,
    )
    .bind(status, text(body.infoVersion, 32) || null, id)
    .run();
  if (result.meta.changes === 0) throw new HttpError(404);
}

const STATUS_ROUTE = /^\/api\/registrations\/([^/]+)\/update-status$/;

async function handleApi(request: Request, env: Env, pathname: string) {
  try {
    const statusMatch = STATUS_ROUTE.exec(pathname);
    if (pathname !== '/api/registrations' && !statusMatch) throw new HttpError(404);

    const body = await readBody(request);
    await ensureSchema(env.DB);
    if (statusMatch) await saveUpdateStatus(decodeURIComponent(statusMatch[1]), body, env.DB);
    else await saveRegistration(body, env.DB);
    return new Response(null, { status: 204 });
  } catch (error) {
    if (!(error instanceof HttpError)) throw error;
    const headers: HeadersInit = error.status === 405 ? { Allow: 'POST' } : {};
    return new Response(error.message || null, { status: error.status, headers });
  }
}

export default {
  fetch(request, env) {
    const { pathname } = new URL(request.url);
    if (pathname.startsWith('/api/')) return handleApi(request, env, pathname);
    return env.ASSETS.fetch(request);
  },
} satisfies ExportedHandler<Env>;
